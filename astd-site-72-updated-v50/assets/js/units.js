/* ชื่อไฟล์รูปของยูนิต (ใช้ทั้งหน้า Units และหน้า Calculator) */
function unitSlug(name){
  return name.toLowerCase()
    .replace(/[^a-z0-9]+/g,"-")
    .replace(/^-+|-+$/g,"") || "unit";
}

/* ============================================================
   รูปยูนิต — ไฟล์ในเครื่อง assets/img/units/<slug>.png (PNG 200x200)
   ไม่เจอไฟล์จะโชว์ตัวอักษรย่อแทน
   Unit artwork — local file assets/img/units/<slug>.png, initials as fallback.
   ============================================================ */
function unitImgSrc(name){
  return `assets/img/units/${unitSlug(name)}.png`;
}
function unitInitials(name){
  return (name.match(/[A-Za-z0-9]/g) || ["?"]).slice(0,2).join("").toUpperCase();
}

